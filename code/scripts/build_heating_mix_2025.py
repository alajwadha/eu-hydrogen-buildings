rows = []
for c, (eu, nat, biocap, h2cap, reno) in D.items():
    avg = {t: (eu[t] + nat[t]) / 2 for t in TECHS}
    s = sum(avg.values())
    fin = {t: avg[t] / s for t in TECHS}
    dr = round(min(0.50, max(0.25, 0.20 + 0.15 * reno)), 3)
    tr = round(min(0.065, max(0.045, 0.045 + 0.015 * reno)), 4)
    div = sum(abs(eu[t] - nat[t]) for t in TECHS)
    rows.append((c, fin, biocap, h2cap, dr, tr, reno, div))

